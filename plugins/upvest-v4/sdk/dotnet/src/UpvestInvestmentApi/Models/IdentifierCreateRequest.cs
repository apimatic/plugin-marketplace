using System.ComponentModel.DataAnnotations;
using System.Text.Json.Serialization;
using UpvestInvestmentApi.Models.Enums;

namespace UpvestInvestmentApi.Models;

/// <summary>
/// Request payload for creating a user identifier used for transaction reporting. Provide <c>type</c> and <c>issuing_country</c>; the <c>identifier</c> value is required unless the <c>identifier_standard</c> is <c>CONCAT</c>.
/// </summary>
public record IdentifierCreateRequest
{
    /// <summary>
    /// Identifier type.
    /// * NATIONAL_ID — national identity card number issued by the user's country.
    /// * PASSPORT — passport number issued by the user's country.
    /// </summary>
    [JsonPropertyName("type")]
    public Type7 Type { get; init; } = Type7.NationalId;

    /// <summary>
    /// Accepted country code. <see href="https://en.wikipedia.org/wiki/ISO_3166-1_alpha-2">ISO 3166-1 alpha-2 codes</see>.
    /// </summary>
    [JsonPropertyName("issuing_country")]
    public required IssuingCountry IssuingCountry { get; init; }

    /// <summary>
    /// Identifier value. Omit this field when <c>identifier_standard</c> is <c>CONCAT</c>: the value is generated by Upvest from the user's name and date of birth. See the User identifiers guide (<see href="https://docs.upvest.co/products/tol/guides/users/users_identifiers">TOL</see> / <see href="https://docs.upvest.co/products/byol/guides/users/users_identifiers">BYOL</see>).
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("identifier")]
    [StringLength(30, MinimumLength = 0)]
    public string? Identifier { get; init; }

    /// <summary>
    /// Identifier standard abbreviation. If it is not provided, the issuing country's 1st priority identifier standard is used by default. Use <c>CONCAT</c> to submit a CONCAT identifier. See the User identifiers guide (<see href="https://docs.upvest.co/products/tol/guides/users/users_identifiers">TOL</see> / <see href="https://docs.upvest.co/products/byol/guides/users/users_identifiers">BYOL</see>).
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("identifier_standard")]
    [MaxLength(6)]
    public string? IdentifierStandard { get; init; }
}
